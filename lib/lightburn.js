function escapeXml(str) {
    if (!str) return '';
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&apos;');
}

/**
 * Builds a valid LightBurn 2 XML project string (.lbrn2)
 */
export function buildLbrn2Xml({
    imageBuffer,
    base64Data,
    widthMm = 100,
    heightMm = 100,
    presetKey = 'hardwood',
    customSettings = {},
    jobName = 'DepthForge 3D Relief',
    makerName = '',
    notes = ''
}) {
    const preset = LIGHTBURN_PRESETS[presetKey] || LIGHTBURN_PRESETS.hardwood;
    const settings = { ...preset, ...customSettings };

    let pngBase64 = base64Data;
    if (!pngBase64 && imageBuffer) {
        pngBase64 = imageBuffer.toString('base64');
    }
    if (!pngBase64) {
        throw new Error('Either imageBuffer or base64Data is required to build a LightBurn project.');
    }

    const xmlNotes = escapeXml(
        `Generated by DepthForge v2.0 (SLCreations, LLC © 2026)\n` +
        `Job: ${jobName}\n` +
        (makerName ? `Maker/Student: ${makerName}\n` : '') +
        `Material: ${settings.material || 'Laser Material'}\n` +
        `Mode: ${settings.mode} | Speed: ${settings.speed} mm/s | Power: ${settings.minPower}% - ${settings.maxPower}%\n` +
        `Interval: ${settings.lineInterval}mm (${settings.dpi} DPI) | Passes: ${settings.numPasses}\n` +
        (notes ? `Notes: ${notes}\n` : '')
    );

    return `<?xml version="1.0" encoding="UTF-8"?>
<LightBurnProject AppVersion="1.7.00" FormatVersion="1" MaterialHeight="0" MirrorX="False" MirrorY="False">
    <Thumbnail Transparent="1"></Thumbnail>
    <CutSetting type="Cut">
        <index Value="0"/>
        <name Value="C00"/>
        <color Value="${settings.color || '#0000ff'}"/>
        <priority Value="0"/>
        <speed Value="${settings.speed}"/>
        <maxPower Value="${settings.maxPower}"/>
        <minPower Value="${settings.minPower}"/>
        <mode Value="${settings.mode || 'Grayscale'}"/>
        <grayscaleSource Value="Grayscale"/>
        <lineInterval Value="${settings.lineInterval}"/>
        <dpi Value="${settings.dpi}"/>
        <numPasses Value="${settings.numPasses}"/>
        <scanAngle Value="${settings.scanAngle || 0}"/>
        <bidirectional Value="${settings.bidirectional ? 1 : 0}"/>
        <airAssist Value="${settings.airAssist ? 1 : 0}"/>
    </CutSetting>
    <Shape Type="Bitmap">
        <CutIndex Value="0"/>
        <X Value="0"/>
        <Y Value="0"/>
        <Width Value="${Math.max(1, Number(widthMm) || 100)}"/>
        <Height Value="${Math.max(1, Number(heightMm) || 100)}"/>
        <Data Format="Base64" Type="PNG">${pngBase64}</Data>
    </Shape>
    <Notes Value="${xmlNotes}"/>
</LightBurnProject>`;
}

// In-Memory Laser Operator Queue with status tracking
class LaserQueueManager {
    constructor() {
        this.queue = [];
    }

    addJob({
        makerName = 'Anonymous Maker',
        makerEmail = '',
        prompt = '',
        imageUrl = '',
        lbrn2Url = '',
        preset = 'hardwood',
        material = 'Hardwood',
        widthMm = 100,
        heightMm = 100,
        notes = ''
    }) {
        const id = 'lbrn_' + crypto.randomUUID().substring(0, 8);
        const job = {
            id,
            makerName: String(makerName).trim() || 'Anonymous Maker',
            makerEmail: String(makerEmail).trim(),
            prompt: String(prompt).trim(),
            imageUrl,
            lbrn2Url,
            preset,
            material,
            widthMm: Number(widthMm) || 100,
            heightMm: Number(heightMm) || 100,
            notes: String(notes).trim(),
            status: 'queued', // 'queued' | 'engraving' | 'completed' | 'cancelled'
            createdAt: new Date().toISOString(),
            updatedAt: new Date().toISOString()
        };
        this.queue.unshift(job);
        // Keep last 100 jobs in memory
        if (this.queue.length > 100) {
            this.queue.pop();
        }
        return job;
    }

    listJobs(limit = 50) {
        return this.queue.slice(0, limit);
    }

    getJob(id) {
        return this.queue.find(j => j.id === id) || null;
    }

    updateStatus(id, newStatus) {
        const valid = ['queued', 'engraving', 'completed', 'cancelled'];
        if (!valid.includes(newStatus)) {
            throw new Error(`Invalid laser job status. Must be one of: ${valid.join(', ')}`);
        }
        const job = this.getJob(id);
        if (!job) return null;
        job.status = newStatus;
        job.updatedAt = new Date().toISOString();
        return job;
    }
}

export const laserQueue = new LaserQueueManager();
